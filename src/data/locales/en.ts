/** Every user-visible string on the site. Derived from the English object. */
export type Strings = typeof en

/**
 * Recursive partial, with arrays as leaves: a translation replaces `bio` and `keywords`
 * wholesale, because a positional merge of differing lengths is nonsense.
 *
 * The array branch has to come first, or `Object`'s index signature swallows arrays and
 * every element becomes optional - a translation could ship a two-paragraph bio.
 */
export type DeepPartial<T> = T extends readonly unknown[]
  ? T
  : T extends object
    ? { [K in keyof T]?: DeepPartial<T[K]> }
    : T
